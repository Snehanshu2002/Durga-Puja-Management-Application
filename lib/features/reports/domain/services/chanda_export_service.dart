import 'dart:convert';
import 'dart:typed_data';
import 'package:csv/csv.dart';
import 'package:intl/intl.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import 'package:durgapuja_manager/core/utils/money_formatter.dart';
import 'package:durgapuja_manager/features/chanda/domain/entities/chanda_target_with_progress.dart';

class ChandaExportService {
  /// Generate printable PDF document for Chanda Member List
  static Future<Uint8List> generateChandaPdf({
    required String organizationName,
    required String eventName,
    required int eventYear,
    required List<ChandaTargetWithProgress> targets,
    required String generatedBy,
  }) async {
    final pdf = pw.Document();
    final dateFormat = DateFormat('dd MMM yyyy, hh:mm a');
    final formattedDate = dateFormat.format(DateTime.now());

    // Calculate Footer Totals
    int totalTarget = 0;
    int totalPaid = 0;
    int totalRemaining = 0;
    int totalExcess = 0;

    for (final item in targets) {
      if (item.isCancelled) continue;
      totalTarget += item.targetAmount;
      totalPaid += item.paidAmount;
      totalRemaining += item.remainingAmount;
      totalExcess += item.excessAmount;
    }

    const brandColor = PdfColor.fromInt(0xFF1E3A8A); // Royal Indigo

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.symmetric(horizontal: 16, vertical: 20),
        header: (context) => pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.start,
                  children: [
                    pw.Text(
                      organizationName.toUpperCase(),
                      style: pw.TextStyle(
                        fontSize: 13,
                        fontWeight: pw.FontWeight.bold,
                        color: brandColor,
                      ),
                    ),
                    pw.Text(
                      'Chanda Target & Collection Sheet - $eventName ($eventYear)',
                      style: pw.TextStyle(
                        fontSize: 11,
                        fontWeight: pw.FontWeight.bold,
                        color: PdfColors.grey900,
                      ),
                    ),
                  ],
                ),
                pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.end,
                  children: [
                    pw.Text(
                      'Report Date: $formattedDate',
                      style: const pw.TextStyle(fontSize: 8.5, color: PdfColors.grey700),
                    ),
                    pw.Text(
                      'Generated by: $generatedBy',
                      style: const pw.TextStyle(fontSize: 8.5, color: PdfColors.grey700),
                    ),
                  ],
                ),
              ],
            ),
            pw.SizedBox(height: 6),
            pw.Divider(color: brandColor, thickness: 1.2),
            pw.SizedBox(height: 6),
          ],
        ),
        footer: (context) => pw.Column(
          children: [
            pw.Divider(color: PdfColors.grey400),
            pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                pw.Text(
                  'Durga Puja Management System - Confidential',
                  style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey600),
                ),
                pw.Text(
                  'Page ${context.pageNumber} of ${context.pagesCount}',
                  style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey600),
                ),
              ],
            ),
          ],
        ),
        build: (context) {
          return [
            pw.TableHelper.fromTextArray(
              headers: [
                'Sl',
                'Member Name',
                'Mobile Number',
                'Target (Rs)',
                'Paid (Rs)',
                'Remaining (Rs)',
                'Excess (Rs)',
                'Status',
                'Signature',
              ],
              data: targets.asMap().entries.map((entry) {
                final index = entry.key + 1;
                final item = entry.value;
                final mobile = item.target.mobileNumber?.trim().isNotEmpty == true
                    ? item.target.mobileNumber!
                    : '-';

                return [
                  index.toString(),
                  item.target.personName,
                  mobile,
                  MoneyFormatter.format(item.targetAmount).replaceAll('₹', 'Rs. '),
                  MoneyFormatter.format(item.paidAmount).replaceAll('₹', 'Rs. '),
                  MoneyFormatter.format(item.remainingAmount).replaceAll('₹', 'Rs. '),
                  item.excessAmount > 0 ? MoneyFormatter.format(item.excessAmount).replaceAll('₹', 'Rs. ') : '-',
                  item.statusLabel,
                  '', // Blank for physical signature
                ];
              }).toList(),
              border: pw.TableBorder.all(color: PdfColors.grey300, width: 0.5),
              headerStyle: pw.TextStyle(
                fontSize: 8.5,
                fontWeight: pw.FontWeight.bold,
                color: PdfColors.white,
              ),
              headerDecoration: const pw.BoxDecoration(color: brandColor),
              cellStyle: const pw.TextStyle(fontSize: 7.8),
              cellPadding: const pw.EdgeInsets.symmetric(horizontal: 4, vertical: 3.5),
              cellAlignment: pw.Alignment.centerLeft,
              cellAlignments: {
                0: pw.Alignment.center,
                2: pw.Alignment.center,
                3: pw.Alignment.centerRight,
                4: pw.Alignment.centerRight,
                5: pw.Alignment.centerRight,
                6: pw.Alignment.centerRight,
                7: pw.Alignment.center,
                8: pw.Alignment.center,
              },
              columnWidths: {
                0: const pw.FixedColumnWidth(20),
                1: const pw.FlexColumnWidth(3.2),
                2: const pw.FlexColumnWidth(2.2),
                3: const pw.FlexColumnWidth(1.8),
                4: const pw.FlexColumnWidth(1.6),
                5: const pw.FlexColumnWidth(1.8),
                6: const pw.FlexColumnWidth(1.4),
                7: const pw.FlexColumnWidth(1.5),
                8: const pw.FlexColumnWidth(2.0),
              },
            ),
            pw.SizedBox(height: 10),

            // Summary Totals Footer Box
            pw.Container(
              padding: const pw.EdgeInsets.symmetric(horizontal: 10, vertical: 8),
              decoration: pw.BoxDecoration(
                color: const PdfColor.fromInt(0xFFEFF6FF), // Soft light blue
                borderRadius: const pw.BorderRadius.all(pw.Radius.circular(6)),
                border: pw.Border.all(color: const PdfColor.fromInt(0xFFDBEAFE), width: 1.0),
              ),
              child: pw.Row(
                mainAxisAlignment: pw.MainAxisAlignment.spaceAround,
                children: [
                  _buildSummaryPdfItem('Total Members', targets.length.toString(), brandColor),
                  _buildSummaryPdfItem('Total Target', MoneyFormatter.format(totalTarget).replaceAll('₹', 'Rs. '), brandColor),
                  _buildSummaryPdfItem('Total Paid', MoneyFormatter.format(totalPaid).replaceAll('₹', 'Rs. '), const PdfColor.fromInt(0xFF059669)),
                  _buildSummaryPdfItem('Total Remaining', MoneyFormatter.format(totalRemaining).replaceAll('₹', 'Rs. '), const PdfColor.fromInt(0xFFDC2626)),
                  _buildSummaryPdfItem('Total Excess', MoneyFormatter.format(totalExcess).replaceAll('₹', 'Rs. '), const PdfColor.fromInt(0xFF0D9488)),
                ],
              ),
            ),
          ];
        },
      ),
    );

    return pdf.save();
  }

  static pw.Widget _buildSummaryPdfItem(String title, String value, PdfColor valueColor) {
    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.center,
      children: [
        pw.Text(
          title,
          style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey700),
        ),
        pw.SizedBox(height: 2),
        pw.Text(
          value,
          style: pw.TextStyle(
            fontSize: 9.5,
            fontWeight: pw.FontWeight.bold,
            color: valueColor,
          ),
        ),
      ],
    );
  }

  /// Print Chanda Sheet directly via device / browser dialogue
  static Future<void> printChandaList({
    required String organizationName,
    required String eventName,
    required int eventYear,
    required List<ChandaTargetWithProgress> targets,
    required String generatedBy,
  }) async {
    final pdfBytes = await generateChandaPdf(
      organizationName: organizationName,
      eventName: eventName,
      eventYear: eventYear,
      targets: targets,
      generatedBy: generatedBy,
    );

    await Printing.layoutPdf(
      onLayout: (_) => pdfBytes,
      name: 'Chanda_List_${eventName}_$eventYear.pdf',
    );
  }

  /// Generate RFC-4180 Excel-compatible CSV string with UTF-8 BOM
  static String generateChandaCsv({
    required String organizationName,
    required String eventName,
    required int eventYear,
    required List<ChandaTargetWithProgress> targets,
  }) {
    final List<List<dynamic>> rows = [
      ['Organization', organizationName],
      ['Event', '$eventName ($eventYear)'],
      ['Export Date', DateFormat('dd-MM-yyyy HH:mm:ss').format(DateTime.now())],
      [],
      [
        'Sl No',
        'Member Name',
        'Mobile Number',
        'Target Amount (INR)',
        'Approved Paid (INR)',
        'Remaining Amount (INR)',
        'Excess Amount (INR)',
        'Status',
        'Signature',
      ],
    ];

    int totalTarget = 0;
    int totalPaid = 0;
    int totalRemaining = 0;
    int totalExcess = 0;

    for (int i = 0; i < targets.length; i++) {
      final item = targets[i];
      if (!item.isCancelled) {
        totalTarget += item.targetAmount;
        totalPaid += item.paidAmount;
        totalRemaining += item.remainingAmount;
        totalExcess += item.excessAmount;
      }

      rows.add([
        i + 1,
        item.target.personName,
        item.target.mobileNumber ?? '',
        item.targetAmount,
        item.paidAmount,
        item.remainingAmount,
        item.excessAmount,
        item.statusLabel,
        '',
      ]);
    }

    // Totals Row
    rows.add([]);
    rows.add([
      'TOTAL',
      '${targets.length} Members',
      '',
      totalTarget,
      totalPaid,
      totalRemaining,
      totalExcess,
      '',
      '',
    ]);

    final csvBody = const ListToCsvConverter().convert(rows);
    // Prepend UTF-8 BOM (\uFEFF) so Excel opens UTF-8 characters properly
    return '\uFEFF$csvBody';
  }

  /// Export & Share CSV file via share_plus or printing byte share
  static Future<void> exportAndShareCsv({
    required String organizationName,
    required String eventName,
    required int eventYear,
    required List<ChandaTargetWithProgress> targets,
  }) async {
    final csvData = generateChandaCsv(
      organizationName: organizationName,
      eventName: eventName,
      eventYear: eventYear,
      targets: targets,
    );

    final bytes = Uint8List.fromList(utf8.encode(csvData));
    final filename = 'Chanda_List_${eventName.replaceAll(" ", "_")}_$eventYear.csv';

    await Printing.sharePdf(
      bytes: bytes,
      filename: filename,
    );
  }
}
